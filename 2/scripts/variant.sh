#!/usr/bin/env bash
# build a policy/prefetcher with some macros overridden
# usage: [KIND=l1d_pref] scripts/variant.sh <policy> <label> [KNOB=VALUE]...
set -euo pipefail
cd "$(dirname "$0")/.."

[ $# -ge 2 ] || { echo "usage: $0 <policy> <label> [KNOB=VALUE]..." >&2
                  exit 1; }
policy=$1 label=$2
shift 2
KIND=${KIND:-l2c_repl}
L1D=${L1D:-no}
L2C=${L2C:-lru}
BUILD=${BUILD:-scripts/build.sh}

case $KIND in
    l2c_repl) dir=replacement ;;
    l1d_pref) dir=prefetcher ;;
    *) echo "KIND must be l2c_repl or l1d_pref" >&2; exit 1 ;;
esac
src=$dir/$policy.$KIND
tmp=$dir/$label.$KIND
[ -f "$src" ] || { echo "no $src" >&2; exit 1; }
[ "$src" != "$tmp" ] || { echo "label must differ from policy" >&2; exit 1; }

trap 'rm -f "$tmp"' EXIT
{
    echo "// generated by scripts/variant.sh from $policy.$KIND"
    for kv in "$@"; do echo "#define ${kv%%=*} ${kv#*=}"; done
    cat "$src"
} > "$tmp"

if [ "$KIND" = l1d_pref ]; then
    "$BUILD" "$label" "$L2C" "$label"
else
    "$BUILD" "$L1D" "$label" "$label"
fi | grep -E "error|successfully|Binary:"
